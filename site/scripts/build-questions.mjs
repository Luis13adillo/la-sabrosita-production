#!/usr/bin/env node
/**
 * Generate CLIENT-QUESTIONS.md — everything this website could not answer for
 * itself, in the client's language rather than in ours.
 *
 * It is generated rather than written so it cannot go stale: the copy gaps come
 * from the catalogue, the brand gaps come from brand.json's own
 * notSpecifiedInSource list, and the design choices come from invented.json. If
 * the client answers one, the answer goes into brand.json or descriptions.json
 * and this file shrinks on the next build.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, '..');
const REPO = path.resolve(SITE, '..');
const brand = JSON.parse(fs.readFileSync(path.join(REPO, 'brand/brand.json'), 'utf8'));
const menu = JSON.parse(fs.readFileSync(path.join(SITE, 'data/menu.json'), 'utf8'));
const invented = JSON.parse(fs.readFileSync(path.join(SITE, 'data/invented.json'), 'utf8'));

const nameOnly = menu.items.filter((i) => i.nameOnly);
const enBlank = menu.items.filter((i) => !i.copy.en && i.copy.es);
const multi = menu.items.filter((i) => i.images.length > 1);

const md = `# Questions for La Sabrosita

Everything the website could not answer for itself. Nothing here is a problem —
each one is a place where we chose to leave a gap rather than fill it with a
guess, because a guess on a menu becomes a promise to a customer.

Generated by \`site/scripts/build-questions.mjs\`. Answer any of these and it
shrinks on the next build.

---

## 1. Four products have no description, in either language

They show on the site as a name and a photograph, and nothing else. That looks
deliberate — the card is designed for it — but if you want a line under them,
one sentence each is all we need.

${nameOnly.map((i) => `- **${i.name}** (${menu.categories.find((c) => c.id === i.category).es})`).join('\n')}

## 2. Three products show a Spanish line but no English one

You told us on 2026-08-17 to leave the English blank for these, because the
product name is already English and there was nothing to translate. That is what
the site does. Confirming it is still what you want:

${enBlank.map((i) => `- **${i.name}** — Spanish reads "${i.copy.es}"`).join('\n')}

## 3. Things about the shop the site does not say

We were not given these, so the site states none of them. It says only
"Swedesboro, New Jersey", which is what the brand guidelines say.

- Street address
- Opening hours
- Phone number
- Instagram / Facebook / TikTok
- Whether you want an online ordering or delivery link

None of these are hard to add. All of them would be wrong if we invented them.

## 4. Prices

There are none anywhere on the site, and \`scripts/smoke.mjs\` fails the build if
anything that looks like a price ever appears. If prices should be shown, that is
a decision to make deliberately — they change, and a stale price on a website is
worse than no price.

## 5. Things the brand guidelines leave open

Your guidelines PDF is the source of truth for the brand, and there are ${brand.notSpecifiedInSource.length}
things it does not define. We had to choose each of them to build a website. Our
choices are written down in \`INVENTED.md\` with the reasoning, and **they are not
brand rules** — if you or your designer decide differently, the answer goes into
\`brand/brand.json\` and the site picks it up on the next build.

${brand.notSpecifiedInSource.map((s) => `- ${s}`).join('\n')}

The two worth your attention:

- **The pink-to-purple gradient.** Page 14 names it but publishes no stops and no
  angle. The site uses it for the hero. Our stops are a guess and are marked as
  one.
- **The logo's clear space.** The rule is "at least the height of the mascot bow
  on every side", which is a measurement of the artwork rather than a number.
  Nobody has measured the bow, so the site uses a deliberate over-estimate.

## 6. One accessibility conflict in the guidelines themselves

Page 17's approved menu card sets its smallest line in electric blue on cream.
Measured, that is 3.1:1 — below the legal minimum for text at any size. The
website therefore does not reuse that treatment for anything a customer needs to
read. Nothing was changed in your guidelines; we just did not copy that one
detail. Worth raising with whoever maintains the PDF.

Similarly, white text on hot pink measures 4.06:1, which is legal for headlines
but not for body text. The site works around it by keeping small text on cream or
deep purple, which is what the guidelines say cream is for anyway.

## 7. Photographs

${menu.counts.images} photographs cover ${menu.counts.products} products. ${multi.length} products have more
than one — the site shows them all, and a customer can flip between them:

${multi.map((i) => `- **${i.name}** — ${i.images.length} photographs`).join('\n')}

If any of these is the wrong shot for a product, or if a product should lead with
a different one, tell us which and we will reorder them. Nothing is regenerated
or retouched; the site reads the approved masters exactly as they are.

## 8. The site is deliberately heavy with pictures

Forty-five products, sixty-two photographs, and the food is very large on purpose
— that is the thing the whole site is for, and it is what a customer sees before
they walk in.

The cost is honest: on wifi the first screen appears in about a fifth of a second.
On a slower mobile connection it takes around four seconds, because the first
screen is about 1.4 MB of photography. We could make it faster, but only by making
the food smaller or the pictures softer, and both undo the reason it works.

If you ever want the trade the other way — a lighter, plainer menu for people on
poor signal — say so and it is a straightforward change.

---

*${invented.groups.length} groups of design decisions are documented in \`INVENTED.md\`.*
`;

fs.writeFileSync(path.join(SITE, 'CLIENT-QUESTIONS.md'), md);
console.log(`CLIENT-QUESTIONS.md — ${nameOnly.length} name-only, ${enBlank.length} Spanish-only, ` +
            `${brand.notSpecifiedInSource.length} open brand values`);
