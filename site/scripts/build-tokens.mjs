#!/usr/bin/env node
/**
 * Generate site/styles/tokens.css and the repo's INVENTED.md.
 *
 * Colour, typeface and logo values are READ FROM brand/brand.json every build.
 * Nothing brand-owned is typed into this file — if the client revises the
 * palette, `npm run tokens` is the whole update. That is the rule in CLAUDE.md:
 * import brand.json, never copy a hex code.
 *
 * Everything brand.json marks null is read from site/data/invented.json, which
 * is also what INVENTED.md is printed from — so the CSS and the disclosure
 * document cannot drift apart.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, '..');
const REPO = path.resolve(SITE, '..');
const brand = JSON.parse(fs.readFileSync(path.join(REPO, 'brand/brand.json'), 'utf8'));
const invented = JSON.parse(fs.readFileSync(path.join(SITE, 'data/invented.json'), 'utf8'));

const P = brand.color.palette;
const hex = (k) => P[k].hex;
const rgb = (k) => P[k].rgb.join(' ');

// Sanity: fail loudly rather than emit a stylesheet with a hole in it.
for (const k of ['hotPink', 'deepPurple', 'electricBlue', 'sunnyYellow', 'baseCream']) {
  if (!P[k]) throw new Error(`brand.json is missing palette.${k}`);
}

const css = `/* GENERATED by scripts/build-tokens.mjs — do not hand-edit.
   Brand values come from brand/brand.json (${brand.brandVersion}, transcribed from
   ${brand.sourceOfTruth.document}). Values brand.json marks null come from
   site/data/invented.json and are disclosed in INVENTED.md. */

:root {
  /* ---- palette: brand.json color.palette, verbatim ---------------------- */
${Object.keys(P).map((k) => `  --c-${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}: ${hex(k)};\n  --c-${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}-rgb: ${rgb(k)};`).join('\n')}
  --c-dark: ${brand.color.contrastFields.darkContrast};

  /* Role names, so a component never reaches for a colour by its own name.
     Roles follow brand.json color.usageRule and the page-17 hierarchy. */
  --c-brand: var(--c-hot-pink);            /* dominant brand field */
  --c-structure: var(--c-deep-purple);     /* contrast and structure */
  --c-accent: var(--c-electric-blue);      /* energy */
  --c-highlight: var(--c-sunny-yellow);    /* energy */
  --c-reading: var(--c-base-cream);        /* reading areas */
  --c-category: var(--c-hot-pink);         /* page 17: CATEGORY TITLE */
  --c-item: var(--c-deep-purple);          /* page 17: Menu Item */
  --c-body: #4a4448;                       /* page 17: description, measured #716C68–#787276 */
  /* page 17's supporting-detail grey samples around #948F8B. That is 3.0:1 on
     cream and fails AA at any size, so it is darkened to the lightest value that
     passes — 5.15:1. The hue is kept. See INVENTED.md. */
  --c-muted: #6f686b;
  --c-note: var(--c-electric-blue);        /* page 17: the blue note line */

  /* ---- typography: brand.json typography ------------------------------- */
  /* brand.json's own fallback stack, with two metric-matched stand-ins inserted
     after the real face. They are not new typefaces — they are Helvetica Neue and
     Arial, which the stack already names, stretched to occupy exactly the space
     Noto Sans will so the webfont swap cannot move the layout. Measured, not
     guessed; the numbers and the reason are in styles/fonts.css. */
  --font: ${(() => {
    const stack = brand.typography.fallbackStack.map((f) => (/\s/.test(f) ? `'${f}'` : f));
    return [stack[0], `'Noto Sans metric Helvetica'`, `'Noto Sans metric Arial'`, ...stack.slice(1)].join(', ');
  })()};
  --w-body: ${brand.typography.roles.body.weight};
  --w-bold: ${brand.typography.roles.headings.weight};

  /* THE DISPLAY FACE. brand.json typography.display — corrected 2026-08-25 —
     asks for a rounded, playful display face for headings and names Fredoka and
     Baloo as references. It does not lock one ("or a comparable rounded display
     typeface"), so the specific pick is an invention and is disclosed in
     INVENTED.md. Everything read here still comes out of brand.json: the family
     order, and both weights. Nothing is typed. */
  --font-display: ${brand.typography.displayFallbackStack.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ')};
  --w-display: ${brand.typography.roles.emphasis.weight};
  --w-semi: ${brand.typography.roles.headings.weight};

  /* ---- everything below: brand.json says null. See INVENTED.md. -------- */
  --fs-item: clamp(1.125rem, 0.9rem + 0.6vw, 1.375rem);
  --fs-desc: clamp(0.875rem, 0.8rem + 0.25vw, 1rem);
  --fs-note: 0.6875rem;
  --fs-section: clamp(1.75rem, 1.1rem + 2.4vw, 3.25rem);
  --fs-display: clamp(2.75rem, 1.2rem + 6.4vw, 7rem);
  --lh-desc: 1.35;
  --lh-tight: 1.05;
  --tracking-caps: 0.06em;

  --s-1: 4px;  --s-2: 8px;  --s-3: 12px; --s-4: 16px;
  --s-5: 24px; --s-6: 32px; --s-7: 40px; --s-8: 48px;
  --s-9: 64px; --s-10: 80px; --s-11: 96px; --s-12: 128px;

  /* Page 17's card padding is 6.0% of the card's own width. Container-query
     units keep that true at any card size, with a floor for small phones. */
  --pad-card: max(14px, 6cqw);

  --r-card: 10px;
  --r-tile: 16px;
  --r-panel: 24px;
  --r-pill: 999px;
  --r-motif: 23%;

  --grad-brand: linear-gradient(160deg, var(--c-hot-pink) 0%, var(--c-deep-purple) 100%);

  --shadow-card: 0 1px 2px rgb(var(--c-deep-purple-rgb) / .06), 0 8px 24px -8px rgb(var(--c-deep-purple-rgb) / .14);
  --shadow-lift: 0 2px 6px rgb(var(--c-deep-purple-rgb) / .10), 0 24px 48px -16px rgb(var(--c-deep-purple-rgb) / .26);
  --shadow-food: drop-shadow(0 18px 22px rgb(var(--c-deep-purple-rgb) / .22));

  --ease: cubic-bezier(.22, 1, .36, 1);
  --ease-spring: cubic-bezier(.34, 1.56, .64, 1);
  --dur-fast: 160ms;
  --dur: 280ms;
  --dur-slow: 560ms;

  /* Footer logo clear space — an over-estimate of one mascot-bow height,
     because the bow has not been measured. The clamp mirrors the footer logo's
     own rendered width so the two cannot drift apart. See INVENTED.md. */
  --foot-clear: calc(clamp(250px, 22vw, 300px) * 0.20);

  --maxw: 1480px;
  --gutter: clamp(16px, 4vw, 64px);

  /* ---- the approved design's own values. brand.json says null for all of
     them: it publishes no type sizes, no letter-spacing, no radii and no
     motion timing. Every one is disclosed in INVENTED.md. ---------------- */
  --tr-caps: 0.06em;      /* = --tracking-caps, kept as one name per role */
  --tr-wide: 0.14em;
  --tr-wider: 0.20em;
  --tr-widest: 0.24em;
  --tr-display: -0.012em;
  --tr-slab: -0.022em;

  --fs-tiny: 11px;
  --fs-chip: 12px;
  --fs-tag: 13px;
  --fs-lede: 19px;

  --r-sign: clamp(20px, 3vw, 44px);
  --r-panel-lg: 26px;
  --r-tile-lg: 20px;

  --drip-h: 6px;
  --bulb-cycle: 2.6s;
  --tick-cycle: 68s;
  --case-cycle: 74s;
  --dust-cycle: 56s;
  --bob-cycle: 7s;
}

@media (prefers-reduced-motion: reduce) {
  :root { --dur-fast: 1ms; --dur: 1ms; --dur-slow: 1ms; }
}
`;
fs.writeFileSync(path.join(SITE, 'styles/tokens.css'), css);

const md = `# INVENTED.md

Values this website chose because \`brand/brand.json\` says \`null\`.

**These are not brand rules.** \`brand/brand.json\` is the official global brand
source of truth, and where it says \`null\` it says so on purpose — the guidelines
PDF genuinely does not publish that value. Everything on this page is a decision
made to ship a website, recorded so nobody later mistakes it for something the
client approved. If the client answers one of these, the answer belongs in
\`brand/brand.json\`, not here.

Generated from \`site/data/invented.json\` by \`site/scripts/build-tokens.mjs\`.
Editing this file by hand will be overwritten; edit the JSON.

Brand version read: **${brand.brandVersion}** — transcribed from \`${brand.sourceOfTruth.document}\`.

${invented.groups.map((g) => `## ${g.title}

**Why this had to be decided.** ${g.why}

**How it was decided.** ${g.method}

| Token | Value | Note |
| --- | --- | --- |
${g.values.map((v) => `| \`${v.token}\` | \`${v.value}\` | ${v.note || '—'} |`).join('\n')}
`).join('\n')}
## What was measured rather than invented

Three of the numbers above came out of the guidelines PDF itself rather than out
of taste. They are recorded here so the measurement can be re-checked:

| Measurement | Source | Value |
| --- | --- | --- |
| Menu card corner radius | page 17, the approved card, rendered at 300 dpi | 32 px arc on a 1406 px wide card = **2.3% of width** |
| Menu card text ratio | page 17, three text levels | **1 : 0.72 : 0.50** (item : description : note) |
| Menu card description line height | page 17, baseline to baseline | **1.35** |
| Menu card padding | page 17, left inset of all three text levels | **6.0% of card width** |
| Motif square corner radius | page 19, the four colour squares | 96 px arc on a 418 px side = **23% of the side** |
| Menu item name colour | page 17, sampled | \`#4E115E\` — the deep purple brand.json already records |
| Supporting note colour | page 17, sampled | \`#1896D7\` — the electric blue brand.json already records |
`;
fs.writeFileSync(path.join(REPO, 'INVENTED.md'), md);
console.log('wrote site/styles/tokens.css and INVENTED.md');
